import streamlit as st
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.dates as mdates
from datetime import datetime, timedelta

# Strategy params
EMA_FAST = 50
EMA_SLOW = 200
RSI_PERIOD = 14
ATR_PERIOD = 14

# --- Indicators ---
def ema(series, n):
    return series.ewm(span=n, adjust=False).mean()

def rsi(series, n=14):
    delta = series.diff()
    up = delta.clip(lower=0)
    down = -delta.clip(upper=0)
    ma_up = up.ewm(alpha=1 / n, adjust=False).mean()
    ma_down = down.ewm(alpha=1 / n, adjust=False).mean()
    rs = ma_up / ma_down
    return 100 - (100 / (1 + rs))

def atr(df, n=14):
    high_low = df['High'] - df['Low']
    high_close = (df['High'] - df['Close'].shift()).abs()
    low_close = (df['Low'] - df['Close'].shift()).abs()
    tr = pd.concat([high_low, high_close, low_close], axis=1).max(axis=1)
    return tr.rolling(n).mean()

# --- Strategy logic ---
def compute_indicators(df):
    df['EMA50'] = ema(df['Close'], EMA_FAST)
    df['EMA200'] = ema(df['Close'], EMA_SLOW)
    df['RSI'] = rsi(df['Close'], RSI_PERIOD)
    df['ATR'] = atr(df, ATR_PERIOD)
    return df

def generate_signals(df):
    df['signal'] = None
    for i in range(1, len(df)):
        prev = df.iloc[i-1]
        curr = df.iloc[i]
        if (curr['EMA50'] < curr['EMA200']) and (prev['Close'] >= prev['EMA50']) and (curr['Close'] < curr['EMA50']):
            if (25 <= curr['RSI'] <= 65) and (curr['RSI'] < prev['RSI']):
                df.at[df.index[i], 'signal'] = 'SELL'
        if (curr['EMA50'] > curr['EMA200']) and (prev['Close'] <= prev['EMA50']) and (curr['Close'] > curr['EMA50']):
            if (35 <= curr['RSI'] <= 75) and (curr['RSI'] > prev['RSI']):
                df.at[df.index[i], 'signal'] = 'BUY'
    return df

# --- Fake data for demo (later replace with broker API) ---
def sample_data(periods=200, start_price=1.30):
    idx = pd.date_range(end=datetime.utcnow(), periods=periods, freq='60min')
    np.random.seed(42)
    returns = np.random.normal(0, 0.001, len(idx))
    price = start_price + np.cumsum(returns)
    openp = price
    closep = price + np.random.normal(0, 0.0003, len(idx))
    highp = np.maximum(openp, closep) + np.abs(np.random.normal(0, 0.0005, len(idx)))
    lowp = np.minimum(openp, closep) - np.abs(np.random.normal(0, 0.0005, len(idx)))
    return pd.DataFrame({'Open': openp, 'High': highp, 'Low': lowp, 'Close': closep}, index=idx)

# --- Streamlit UI ---
st.set_page_config(page_title="🦄 Unicorn Trading Bot", layout="wide")
st.title("🦄 Unicorn Strategy Bot Dashboard")

df = sample_data()
df = compute_indicators(df)
df = generate_signals(df)

# Show last signal
last = df.iloc[-1]
st.subheader(f"📢 Current Signal: **{last['signal']}**")
st.write({
    'Close': round(last['Close'], 5),
    'EMA50': round(last['EMA50'], 5),
    'EMA200': round(last['EMA200'], 5),
    'RSI': round(last['RSI'], 2),
    'ATR': round(last['ATR'], 5)
})

