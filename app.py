fig, ax = plt.subplots(figsize=(12,6))

# Candlesticks
for i in range(len(df)):
    color = 'g' if df['Close'].iloc[i] >= df['Open'].iloc[i] else 'r'
    ax.plot([df.index[i], df.index[i]], [df['Low'].iloc[i], df['High'].iloc[i]], color=color)
    ax.plot([df.index[i], df.index[i]], [df['Open'].iloc[i], df['Close'].iloc[i]], linewidth=6, color=color)

# EMAs
ax.plot(df.index, df['EMA50'], label="EMA50", color="blue", linewidth=1)
ax.plot(df.index, df['EMA200'], label="EMA200", color="orange", linewidth=1)

# Signals
buy_signals = df[df['signal'] == 'BUY']
sell_signals = df[df['signal'] == 'SELL']
ax.scatter(buy_signals.index, buy_signals['Close'], marker='^', color='lime', label="BUY", s=120)
ax.scatter(sell_signals.index, sell_signals['Close'], marker='v', color='red', label="SELL", s=120)

ax.legend()
